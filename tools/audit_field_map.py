"""Audit the job-table field map by comparing the accessor to the raw byte.

A field whose offset is right matches on every entry. A field that mismatches
everywhere has the wrong offset. A field that mismatches on some entries is
doing something conditional, and is worth reading the code for.
"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from emulate import Gba

ROM = "D:/Nintendo - Game Boy Advance/Final Fantasy Tactics Advance.gba"
ACC = 0x080C8570
BASE = 0x08521A14 - 0x08000000
STRIDE, COUNT = 0x34, 116

FIELD_OFF = {
    0x00: 0x00, 0x01: 0x04, 0x02: 0x06, 0x03: 0x06, 0x04: 0x07, 0x05: 0x09,
    0x06: 0x0b, 0x07: 0x0b, 0x08: 0x0c, 0x09: 0x0d, 0x0a: 0x0e, 0x0b: 0x0f,
    0x0c: 0x10, 0x0d: 0x11, 0x0e: 0x12, 0x0f: 0x12, 0x10: 0x13, 0x11: 0x13,
    0x12: 0x13, 0x13: 0x14, 0x14: 0x14, 0x15: 0x15, 0x16: 0x16, 0x17: 0x17,
    0x18: 0x18, 0x19: 0x19, 0x1a: 0x1a, 0x1b: 0x1b, 0x1c: 0x1d, 0x1d: 0x1e,
    0x1e: 0x2d, 0x1f: 0x2e, 0x20: 0x2f, 0x21: 0x31, 0x22: 0x2b, 0x23: 0x2b,
    0x24: 0x32, 0x25: 0x33, 0x29: 0x25, 0x2a: 0x26, 0x2b: 0x27, 0x2c: 0x28,
    0x2d: 0x29, 0x2e: 0x2a, 0x2f: 0x26,
}

rom = open(ROM, "rb").read()
gba = Gba(ROM)
ent = lambda i, o: rom[BASE + i * STRIDE + o]

print(f"{'field':>6} {'off':>5} {'match':>7} {'verdict'}")
print("-" * 58)
partial = []
for fid in sorted(FIELD_OFF):
    off = FIELD_OFF[fid]
    ok = sum(1 for i in range(COUNT) if gba.call(ACC, [i, 0, fid]) == ent(i, off))
    if ok == COUNT:
        v = "offset confirmed"
    elif ok == 0:
        v = "never matches -> wrong offset or derived value"
    else:
        v = f"conditional ({COUNT - ok} entries differ)"
        partial.append(fid)
    print(f"  {fid:#04x} {off:#5x} {ok:>4}/{COUNT}  {v}")

print(f"\nfields that are conditional: {[hex(f) for f in partial]}")
